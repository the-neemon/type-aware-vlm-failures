"""Tables and figures for the final report, generated from results/ only.

    python scripts/final_assets.py

Writes paper/final/tables/{e4,e5}.tex and paper/final/figures/e5_risk_coverage.pdf.
Captions are left to the section's writer (the course requires the report text
to be written by the team); each table carries its source file in a comment.
Fonts are embedded as TrueType (pdf.fonttype 42), never Type 3.
"""

from __future__ import annotations

import json
import pathlib
import sys

import matplotlib

matplotlib.use("Agg")
matplotlib.rcParams.update({"pdf.fonttype": 42, "ps.fonttype": 42,
                            "font.family": "serif", "font.size": 8})
import matplotlib.pyplot as plt  # noqa: E402

ROOT = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from src.intervene.matrix import Outcome, did_with_ci, recovery_matrix  # noqa: E402

MODELS = {"qwen2_5_vl_7b": "Qwen2.5-VL-7B", "llava_next_mistral_7b": "LLaVA-NeXT-7B"}
REPAIRS = [("I_reask", "Re-ask"), ("I_upsample", "Upsample"), ("I_crop", "Crop"),
           ("I_verify", "Verify")]
TYPES = [("structural", "Misread"), ("fabrication", "Made-up number"), ("zero", "``0''")]
POLICIES = [("plain", "Plain model"), ("binary", "Binary abstention"),
            ("missing", "Missing-bar abstention"), ("controller", "Controller"),
            ("relook_binary", "Re-look + binary abstention"), ("oracle", "Oracle")]
OUT_T, OUT_F = ROOT / "paper/final/tables", ROOT / "paper/final/figures"


def _read(path):
    return [json.loads(l) for l in path.read_text(encoding="utf-8").splitlines() if l.strip()]


def signed(x: float, digits: int = 3) -> str:
    """A signed number with a real minus sign in LaTeX text."""
    return f"{x:+.{digits}f}".replace("-", "$-$")


def e4_outcomes(model):
    rows = [r for p in ("synth_pilot", "synth_pilot2")
            for r in _read(ROOT / f"results/e4/{model}_{p}.outcomes.jsonl") if r.get("applicable")]
    return [Outcome(r["figure_id"], r["failure_type"], r["intervention"], r["recovered"])
            for r in rows]


def e4_table() -> str:
    lines = ["% Generated by scripts/final_assets.py from results/e4/*.outcomes.jsonl",
             "% (pilots 1 and 2 pooled; see results/e4.md). Caption: to be written.",
             r"\begin{table}[t]", r"\centering\small", r"\setlength{\tabcolsep}{3pt}",
             r"\begin{tabular}{lr" + "c" * len(REPAIRS) + "}", r"\toprule",
             r"Original answer & $n$ & " + " & ".join(n for _, n in REPAIRS) + r" \\"]
    for key, name in MODELS.items():
        out = e4_outcomes(key)
        m = recovery_matrix(out)
        n = {t: sum(o.failure_type == t and o.intervention == "I_0" for o in out) for t, _ in TYPES}
        lines += [r"\midrule", rf"\multicolumn{{{2 + len(REPAIRS)}}}{{l}}{{\textit{{{name}}}}} \\"]
        for t, tname in TYPES:
            best = max(m[(t, iv)] for iv, _ in REPAIRS)
            cells = [(rf"\textbf{{{m[(t, iv)]:.2f}}}" if m[(t, iv)] == best and best > 0
                      else f"{m[(t, iv)]:.2f}") for iv, _ in REPAIRS]
            lines.append(f"{tname} & {n[t]} & " + " & ".join(cells) + r" \\")
        d = did_with_ci(out, "I_crop")
        lo, hi = d["ci95"]
        lines.append(rf"\quad crop DiD & & \multicolumn{{{len(REPAIRS)}}}{{c}}"
                     rf"{{{signed(d['delta'])} [{signed(lo)}, {signed(hi)}]}} \\")
    lines += [r"\bottomrule", r"\end{tabular}", r"\caption{TODO}", r"\label{tab:e4}",
              r"\end{table}"]
    return "\n".join(lines) + "\n"


def e5_results():
    return {k: json.loads((ROOT / f"results/e5/{k}_e5.json").read_text()) for k in MODELS}


def e5_table(res) -> str:
    lines = ["% Generated by scripts/final_assets.py from results/e5/*_e5.json",
             "% (see results/e5.md). AURC: mean risk over the risk-coverage curve, lower",
             "% is better; brackets are 95% cluster-bootstrap intervals. Caption: to be written.",
             r"\begin{table}[t]", r"\centering\small", r"\setlength{\tabcolsep}{3pt}",
             r"\begin{tabular}{lcc}", r"\toprule", r"Policy & AURC & 95\% CI \\"]
    for k, model in MODELS.items():
        lines += [r"\midrule", rf"\multicolumn{{3}}{{l}}{{\textit{{{model}}}}} \\"]
        for p, name in POLICIES:
            e = res[k]["policies"][p]
            lo, hi = e["aurc_ci95"]
            lines.append(f"{name} & {e['aurc']:.3f} & [{lo:.3f}, {hi:.3f}] \\\\")
        for a, name in (("re-look beyond binary abstention", "re-look gain (binary)"),
                        ("re-look beyond missing-bar abstention", "re-look gain (missing-bar)")):
            e = res[k]["ablations"][a]
            lo, hi = e["ci95"]
            lines.append(f"\\quad {name} & {signed(e['aurc_difference'])} & "
                         f"[{signed(lo)}, {signed(hi)}] \\\\")
    lines += [r"\bottomrule", r"\end{tabular}", r"\caption{TODO}", r"\label{tab:e5}",
              r"\end{table}"]
    return "\n".join(lines) + "\n"


def e5_figure(res, path):
    styles = {"plain": ("0.6", ":"), "binary": ("#1f77b4", "-"), "missing": ("#2ca02c", "--"),
              "controller": ("#d62728", "-"), "relook_binary": ("#9467bd", "-."),
              "oracle": ("black", "-")}
    fig, axes = plt.subplots(1, 2, figsize=(3.3, 2.1), sharey=True)
    for ax, (k, name) in zip(axes, MODELS.items()):
        for p, label in POLICIES:
            risk = res[k]["policies"][p]["curve"]
            n = len(risk)
            cov = [(i + 1) / n for i in range(n)]
            color, ls = styles[p]
            ax.plot(cov, risk, color=color, ls=ls, lw=1.0, label=label)
        ax.set_title(name, fontsize=8)
        ax.set_xlabel("Coverage")
        ax.set_xlim(0, 1)
        ax.set_ylim(0, 1)
        ax.grid(alpha=0.25, lw=0.4)
    axes[0].set_ylabel("Risk (error rate)")
    fig.tight_layout(pad=0.3, rect=(0, 0.2, 1, 1))
    fig.legend(*axes[0].get_legend_handles_labels(), loc="lower center", ncol=2,
               fontsize=6, frameon=False, bbox_to_anchor=(0.5, 0.0))
    fig.savefig(path, bbox_inches="tight")
    plt.close(fig)


def main():
    OUT_T.mkdir(parents=True, exist_ok=True)
    OUT_F.mkdir(parents=True, exist_ok=True)
    (OUT_T / "e4.tex").write_text(e4_table(), encoding="utf-8")
    res = e5_results()
    (OUT_T / "e5.tex").write_text(e5_table(res), encoding="utf-8")
    e5_figure(res, OUT_F / "e5_risk_coverage.pdf")
    print("wrote", *(str(p.relative_to(ROOT)) for p in
                     (OUT_T / "e4.tex", OUT_T / "e5.tex", OUT_F / "e5_risk_coverage.pdf")))


if __name__ == "__main__":
    main()
